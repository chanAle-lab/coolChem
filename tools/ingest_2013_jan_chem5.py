def extract_figures():
    doc = fitz.open(QP_PDF)
    crops = [
        (4, (85, 95, 520, 165), Q2_FIG),
        (8, (100, 95, 465, 258), Q3C_FIG),
        (10, (90, 95, 525, 170), Q4_FIG),
        (16, (105, 155, 470, 360), Q7_FIG),
    ]
    mat = fitz.Matrix(2.5, 2.5)
    for page_num, rect_coords, rel_path in crops:
        page = doc[page_num - 1]
        pix = page.get_pixmap(matrix=mat, clip=fitz.Rect(*rect_coords))
        out_path = os.path.join(ROOT, rel_path)
        pix.save(out_path, jpg_quality=92)


def main():
    extract_figures()

    with open(DB_PATH, "r", encoding="utf-8") as f:
        db = json.load(f)

    db["papers"] = [p for p in db["papers"] if p["id"] != PAPER_ID]
    db["papers"].append(PAPER_OBJ)

    db["questions"] = [q for q in db["questions"] if q.get("paper") != PAPER_ID]

    for q in QUESTIONS:
        q_slug = q["id"].split("-")[-1]
        ms_rel = f"img/{PAPER_ID}/ms/{q_slug}.png"
        ms_abs = os.path.join(ROOT, ms_rel)
        render_official_markscheme_image(
            question_label=q["ms_label"],
            answers_html=q["ms_ans"],
            extra_html=q["ms_extra"],
            marks=q["ms_marks"],
            spec_ref=q["specRef"],
            output_path=ms_abs,
        )

        q_obj = {
            "id": q["id"],
            "paper": PAPER_ID,
            "year": PAPER_OBJ["year"],
            "series": PAPER_OBJ["series"],
            "unit": PAPER_OBJ["unit"],
            "level": PAPER_OBJ["level"],
            "question": q["questionNumber"],
            "questionNumber": q["questionNumber"],
            "page": q["page"],
            "marks": q["marks"],
            "topics": q["topics"],
            "skills": q["skills"],
            "summary": q["summary"],
            "specRef": q["specRef"],
            "image": f"img/{PAPER_ID}/{q_slug}.jpg",
            "markscheme": ms_rel,
            "figures": q.get("figures", []),
        }
        if "crop_exclude_y" in q:
            q_obj["crop_exclude_y"] = q["crop_exclude_y"]

        db["questions"].append(q_obj)

    with open(DB_PATH, "w", encoding="utf-8") as f:
        json.dump(db, f, indent=2, ensure_ascii=False)

    print(f"Ingested {PAPER_ID}: {len(QUESTIONS)} questions, {sum(q['marks'] for q in QUESTIONS)} marks.")


if __name__ == "__main__":
    main()
