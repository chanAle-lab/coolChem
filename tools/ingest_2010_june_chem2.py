def save_figure(doc, page_num, y0, y1, out_path):
    page = doc[page_num - 1]
    clip = fitz.Rect(25, y0, page.rect.width - 25, y1)
    pix = page.get_pixmap(dpi=200, clip=clip)
    pix.save(out_path)
    print(f"Saved figure {os.path.relpath(out_path, ROOT)}")


def main():
    doc = fitz.open(QP_PDF)
    save_figure(doc, 2, 198, 385, os.path.join(IMG_DIR, "fig-q1-profile.jpg"))
    save_figure(doc, 4, 208, 255, os.path.join(IMG_DIR, "fig-q2-table.jpg"))
    save_figure(doc, 16, 198, 310, os.path.join(IMG_DIR, "fig-q8-processes.jpg"))
    save_figure(doc, 20, 108, 440, os.path.join(IMG_DIR, "fig-q9-extraction.jpg"))

    with open(DB_PATH, "r", encoding="utf-8") as f:
        db = json.load(f)

    db["papers"] = [p for p in db["papers"] if p["id"] != PAPER_ID]
    db["papers"].append(PAPER_OBJ)
    db["questions"] = [q for q in db["questions"] if q.get("paper") != PAPER_ID]

    total_marks = 0
    for q in QUESTIONS:
        total_marks += q["marks"]
        q_num = q["questionNumber"]
        q_slug = q["id"].split("-")[-1]
        ms_rel = f"img/{PAPER_ID}/ms/{q_slug}.png"
        ms_abs = os.path.join(ROOT, ms_rel)

        render_official_markscheme_image(
            question_label=q["ms_label"],
            answers_html=q["ms_ans"],
            extra_html=q["ms_extra"],
            marks=q["ms_marks"],
            spec_ref=q["specRef"],
            output_path=ms_abs,
        )

        db["questions"].append({
            "id": q["id"],
            "paper": PAPER_ID,
            "year": PAPER_OBJ["year"],
            "series": PAPER_OBJ["series"],
            "unit": PAPER_OBJ["unit"],
            "level": PAPER_OBJ["level"],
            "question": q_num,
            "questionNumber": q_num,
            "page": q["page"],
            "marks": q["marks"],
            "topics": q["topics"],
            "skills": q["skills"],
            "summary": q["summary"],
            "specRef": q["specRef"],
            "image": f"img/{PAPER_ID}/{q_slug}.jpg",
            "markscheme": ms_rel,
            "figures": q.get("figures", []),
        })

    with open(DB_PATH, "w", encoding="utf-8") as f:
        json.dump(db, f, indent=2, ensure_ascii=False)

    print(f"Ingested {PAPER_ID}: {len(QUESTIONS)} questions, {total_marks} marks.")


if __name__ == "__main__":
    main()
