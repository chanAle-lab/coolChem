    doc = fitz.open(QP_PDF)
    save_figure(doc, 3, 198, 340, os.path.join(IMG_DIR, "fig-q1-stem.jpg"))
    save_figure(doc, 4, 120, 320, os.path.join(IMG_DIR, "fig-q1-mech.jpg"))
