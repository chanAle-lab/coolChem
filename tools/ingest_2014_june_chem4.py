def extract_figures():
    doc = fitz.open(QP_PDF)
    out_dir = os.path.join(ROOT, "img", PAPER_ID)
    os.makedirs(out_dir, exist_ok=True)
    for fig in FIGURES:
        page = doc[fig["page"] - 1]
        rect = fitz.Rect(*fig["rect"])
        pix = page.get_pixmap(clip=rect, dpi=220)
        out_path = os.path.join(out_dir, fig["file"])
        pix.save(out_path)
        print(f"Saved figure {fig['file']} ({pix.width}x{pix.height})")


def main():
    assert sum(q["marks"] for q in QUESTIONS) == 100, f"Marks={sum(q['marks'] for q in QUESTIONS)}"
    extract_figures()

    db_path = os.path.join(ROOT, "questions.json")
    with open(db_path, "r", encoding="utf-8") as f:
        db = json.load(f)

    db["papers"] = [p for p in db["papers"] if p["id"] != PAPER_ID]
    db["papers"].append(PAPER_OBJ)
    db["questions"] = [q for q in db["questions"] if q["paper"] != PAPER_ID]

    ms_dir = os.path.join(ROOT, "img", PAPER_ID, "ms")
    os.makedirs(ms_dir, exist_ok=True)

    for q in QUESTIONS:
        q_slug = q["id"].split("-")[-1]
        ms_rel = f"img/{PAPER_ID}/ms/{q_slug}.png"
        ms_abs = os.path.join(ROOT, ms_rel)
        render_official_markscheme_image(
            question_label=q["ms_label"],
            answers_html=q["ms_ans"],
            extra_html=q["ms_extra"],
            marks=q["ms_marks"],
            spec_ref=q["specRef"],
            output_path=ms_abs,
        )
        q_entry = {
            "id": q["id"],
            "paper": PAPER_ID,
            "year": PAPER_OBJ["year"],
            "series": PAPER_OBJ["series"],
            "unit": PAPER_OBJ["unit"],
            "level": PAPER_OBJ["level"],
            "question": q["questionNumber"],
            "questionNumber": q["questionNumber"],
            "page": q["page"],
            "marks": q["marks"],
            "topics": q["topics"],
            "skills": q["skills"],
            "summary": q["summary"],
            "specRef": q["specRef"],
            "image": f"img/{PAPER_ID}/{q_slug}.jpg",
            "markscheme": ms_rel,
            "figures": q.get("figures", []),
        }
        if "crop_exclude_y" in q:
            q_entry["crop_exclude_y"] = q["crop_exclude_y"]
        db["questions"].append(q_entry)

    with open(db_path, "w", encoding="utf-8") as f:
        json.dump(db, f, indent=2, ensure_ascii=False)

    print(f"Ingested {len(QUESTIONS)} questions ({sum(q['marks'] for q in QUESTIONS)} marks) for {PAPER_ID}")


if __name__ == "__main__":
    main()
