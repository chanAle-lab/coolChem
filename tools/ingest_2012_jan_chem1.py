def extract_figures():
    doc = fitz.open(QP_PDF)
    crops = [
        (4, (40, 505, 560, 588), "fig-q2c-table.jpg"),
        (5, (40, 95, 560, 378), "fig-q2d-graph.jpg"),
        (7, (40, 592, 560, 682), "fig-q3e-compound.jpg"),
        (14, (40, 95, 560, 275), "fig-q7a-spectrum.jpg"),
    ]
    mat = fitz.Matrix(2.0, 2.0)
    for page_num, rect, fname in crops:
        page = doc[page_num - 1]
        pix = page.get_pixmap(matrix=mat, clip=fitz.Rect(*rect))
        pix.save(os.path.join(IMG_DIR, fname))


def main():
    extract_figures()
    with open(DB_PATH, "r", encoding="utf-8") as f:
        db = json.load(f)

    papers = [p for p in db["papers"] if p["id"] != PAPER_ID]
    papers.append(PAPER_OBJ)
    db["papers"] = papers

    questions = [q for q in db["questions"] if q.get("paper") != PAPER_ID]

    for q in QUESTIONS:
        q_slug = q["id"].split("-")[-1]
        ms_rel = f"img/{PAPER_ID}/ms/{q_slug}.png"
        ms_abs = os.path.join(ROOT, ms_rel)
        render_official_markscheme_image(
            question_label=q["ms_label"],
            answers_html=q["ms_ans"],
            extra_html=q["ms_extra"],
            marks=q["ms_marks"],
            spec_ref=q["specRef"],
            output_path=ms_abs,
        )
        q_entry = {
            "id": q["id"],
            "paper": PAPER_ID,
            "year": PAPER_OBJ["year"],
            "series": PAPER_OBJ["series"],
            "unit": PAPER_OBJ["unit"],
            "level": PAPER_OBJ["level"],
            "question": q["questionNumber"],
            "questionNumber": q["questionNumber"],
            "page": q["page"],
            "marks": q["marks"],
            "topics": q["topics"],
            "skills": q["skills"],
            "summary": q["summary"],
            "specRef": q["specRef"],
            "image": f"img/{PAPER_ID}/{q_slug}.jpg",
            "markscheme": ms_rel,
            "figures": q.get("figures", []),
        }
        if "crop_exclude_y" in q:
            q_entry["crop_exclude_y"] = q["crop_exclude_y"]
        questions.append(q_entry)

    db["questions"] = questions
    with open(DB_PATH, "w", encoding="utf-8") as f:
        json.dump(db, f, indent=2, ensure_ascii=False)

    total_m = sum(q["marks"] for q in QUESTIONS)
    print(f"Ingested {PAPER_ID}: {len(QUESTIONS)} questions, {total_m} marks.")


if __name__ == "__main__":
    main()
